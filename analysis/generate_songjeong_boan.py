def is_point_in_polygon(lat, lon, polygon):
    """
    Ray Casting 알고리즘으로 위경도 좌표가 다각형 내부 영역에 속하는지 정밀 판별합니다.
    """
    n = len(polygon)
    inside = False
    p1_lat, p1_lon = polygon[0]
    for i in range(n + 1):
        p2_lat, p2_lon = polygon[i % n]
        if lon > min(p1_lon, p2_lon):
            if lon <= max(p1_lon, p2_lon):
                if lat <= max(p1_lat, p2_lat):
                    if p1_lon != p2_lon:
                        xinters = (lon - p1_lon) * (p2_lat - p1_lat) / (
                            p2_lon - p1_lon
                        ) + p1_lat
                    if p1_lat == p2_lat or lat <= xinters:
                        inside = not inside
        p1_lat, p1_lon = p2_lat, p2_lon
    return inside


def is_point_included(lat, lon):
    # 1) 포함 구역(구역1, 구역2) 내부인가?
    included = False
    for poly in ALL_INCLUDE_POLYGONS:
        if is_point_in_polygon(lat, lon, poly):
            included = True
            break
    if not included:
        return False

    # 2) 제외 구역(건영아파트, 송원초, 서울숲아이파크 등) 내부인가?
    for ex_poly in ALL_EXCLUDE_POLYGONS:
        if is_point_in_polygon(lat, lon, ex_poly):
            return False

    return True


def generate_songjeong_boan_data():
    """
    구역1 + 구역2 멀티 다각형 영역 내에서
    건영아파트, 송원초등학교, 서울숲아이파크 제외 구역을 차단하고 25m 간격으로 목업 보안등 CSV를 생성합니다.
    """
    random.seed(42)
    rows = []

    all_pts = POLYGON_ZONE_1 + POLYGON_ZONE_2
    lats = [p[0] for p in all_pts]
    lons = [p[1] for p in all_pts]

    lat_min, lat_max = min(lats), max(lats)
    lon_min, lon_max = min(lons), max(lons)

    lat_steps = 60
    lon_steps = 60

    idx = 1
    for i in range(lat_steps):
        lat = lat_min + (lat_max - lat_min) * (i / lat_steps)
        for j in range(lon_steps):
            lon = lon_min + (lon_max - lon_min) * (j / lon_steps)

            lat_jitter = random.uniform(-0.00008, 0.00008)
            lon_jitter = random.uniform(-0.00008, 0.00008)
            cur_lat = lat + lat_jitter
            cur_lon = lon + lon_jitter

            if is_point_included(cur_lat, cur_lon):
                install_type = random.choice(["한전주", "전용주", "건축물"])
                rows.append(
                    {
                        "보안등위치명": f"송정동{idx:03d}",
                        "설치개수": 1,
                        "소재지도로명주소": f"서울특별시 성동구 송정동 {random.randint(1, 150)}-{random.randint(1, 30)}",
                        "소재지지번주소": f"서울특별시 성동구 송정동 {random.randint(1, 150)}-{random.randint(1, 30)}",
                        "위도": round(cur_lat, 7),
                        "경도": round(cur_lon, 7),
                        "설치연도": random.randint(2018, 2024),
                        "설치형태": install_type,
                        "관리기관전화번호": "02-2286-5114",
                        "관리기관명": "서울특별시 성동구청",
                        "데이터기준일자": "2025-12-23",
                    }
                )
                idx += 1

    df = pd.DataFrame(rows)
    os.makedirs(os.path.dirname(OUTPUT_CSV), exist_ok=True)
    df.to_csv(OUTPUT_CSV, index=False, encoding="utf-8-sig")
    print(
        f"[OK] Songjeong-dong Boan CSV Generated! Total rows: {len(df)} -> {OUTPUT_CSV}"
    )
    return df


if __name__ == "__main__":
    generate_songjeong_boan_data()
